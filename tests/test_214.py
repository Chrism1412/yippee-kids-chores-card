# 2.0.0: 🧩 Einstellungen mit Kacheln als Startseite · 📖 Handbuch in Kapiteln
from playwright.sync_api import sync_playwright
import datetime, atexit
R=[]
def ok(n,c,x=''): R.append(('OK ' if c else 'FAIL ')+n+' '+str(x)[:300])
atexit.register(lambda: print('\n'.join(R)))
with sync_playwright() as p:
    b=p.chromium.launch(); pg=b.new_page(viewport={'width':430,'height':900}); errs=[]
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.clock.install(time=datetime.datetime.fromisoformat('2026-12-01T09:30:00'))
    pg.goto('http://localhost:8765/kp_test.html'); pg.clock.run_for(1500); ev=pg.evaluate; t=lambda ms=600: pg.clock.run_for(ms)
    ev("A._save('kid','K',{name:'Mia',emoji:'🦊',points:10,total:10}); A._setCfg({approval:false,setView:'all',wheelOn:true})"); t(800)
    ev("document.getElementById('b').style.display='none'; A._accAll=false; A._accOpen=''; A._tab='einst'; A._render()"); t(1200)
    S="A.shadowRoot"
    vis=lambda sel: ev(f"[...{S}.querySelectorAll('{sel}')].filter(e=>e.offsetParent!==null).length")
    ok('tiles shown', vis('.settile')==9, vis('.settile'))
    ok('sections hidden on start', vis('.accw > .acc')==0 and ev(f"{S}.querySelector('.accw').hidden"))
    ok('tile has count', 'von' in ev(f"{S}.querySelector('.settile[data-g=\"4\"] em').textContent") and '1 von 5 an' in ev(f"{S}.querySelector('.settile[data-g=\"4\"] em').textContent"), ev(f"{S}.querySelector('.settile[data-g=\"4\"]').textContent"))
    ev(f"{S}.querySelector('.settile[data-g=\"4\"]').click()"); t(800)
    ok('group opened', vis('.settile')==0 and vis('.setback')==1)
    ids=ev(f"[...{S}.querySelectorAll('.accw > .acc')].filter(e=>!e.hidden).map(e=>e.querySelector('.acch').dataset.id)")
    ok('only that group', ids==['f_wheelOn','f_stkOn','f_eggOn','f_hwOn','f_rdOn'], ids)
    ev(f"{S}.querySelector('.acch[data-id=f_wheelOn]').click()"); t(800)
    ok('section opens in group', ev(f"!!{S}.querySelector('.acc.open .acch[data-id=f_wheelOn]')") and vis('.setback')==1)
    pg.locator('.setq').fill('sprache'); t(500)
    ok('search searches all groups', vis('.settile')==0 and vis('.setback')==0 and ev(f"[...{S}.querySelectorAll('.accw > .acc')].filter(e=>!e.hidden).some(e=>e.dataset.g!=='4')"))
    pg.locator('.setq').fill(''); t(500); ev("A.shadowRoot.activeElement && A.shadowRoot.activeElement.blur()"); t(300)
    ok('empty search back to group', vis('.setback')==1 and ev(f"[...{S}.querySelectorAll('.accw > .acc')].filter(e=>!e.hidden).every(e=>e.dataset.g==='4')"))
    ev(f"{S}.querySelector('.setback').click()"); t(800)
    ok('back to tiles', vis('.settile')==9 and vis('.setback')==0)
    ev("A._accOpen='look'; A._render()"); t(800)
    ok('deep link opens its group', ev("A._setG")==0 and ev(f"!!{S}.querySelector('.acc.open .acch[data-id=look]')"))
    ev("A._setG=null; A._accOpen=''; A._accAll=true; A._render()"); t(800)
    ok('accAll shows all, no tiles', not ev(f"!!{S}.querySelector('.settiles')") and vis('.accw > .acc')>30)
    ev("A._accAll=false; A._setCfg({setView:'simple'})"); t(800)
    ok('simple view without tiles', not ev(f"!!{S}.querySelector('.settiles')"))
    ev("A._setCfg({setView:'all'})"); t(500)
    # ---------- Handbuch ----------
    ev("A._hbOpen('')"); pg.wait_for_timeout(2000); t(300)
    M=f"{S}.querySelector('#modal')"
    ok('manual chapters', ev(f"{M}.querySelectorAll('.hbch').length")==9)
    ok('chapters closed', ev(f"[...{M}.querySelectorAll('.hbi')].every(e=>e.hidden)"))
    tot=ev(f"[...{M}.querySelectorAll('.hbch small')].reduce((a,e)=>a+Number(e.textContent),0)")
    ok('all topics in chapters', tot==57 and ev(f"{M}.querySelectorAll('.hbi').length")==57, tot)
    ev(f"{M}.querySelector('.hbch[data-c=\"4\"]').click()"); t(400)
    ids=ev(f"[...{M}.querySelectorAll('.hbi')].filter(e=>!e.hidden).map(e=>e.querySelector('summary').textContent)")
    ok('fun chapter opens', len(ids)==8 and ev(f"{M}.querySelector('.hbch[data-c=\"4\"]').classList.contains('on')"), ids)
    pg.locator('#modal .hbq').fill('Glücksrad'); t(400)
    ok('search: no chapters, hits', ev(f"[...{M}.querySelectorAll('.hbch')].every(e=>e.hidden)") and ev(f"[...{M}.querySelectorAll('.hbi')].some(e=>!e.hidden)"))
    pg.locator('#modal .hbq').fill(''); t(400)
    ok('cleared: chapters again', ev(f"[...{M}.querySelectorAll('.hbch')].every(e=>!e.hidden)"))
    ev("A._closeModal(); A._hbOpen('', 'reading')"); pg.wait_for_timeout(800); t(300)
    ok('topic link shows only topic', ev(f"[...{M}.querySelectorAll('.hbi')].filter(e=>!e.hidden).length")==1 and ev(f"[...{M}.querySelectorAll('.hbch')].every(e=>e.hidden)"))
    ok('no errors', not errs, errs)
    b.close()
