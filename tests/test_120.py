from playwright.sync_api import sync_playwright
import datetime
R=[]
def ok(n,c,x=''): R.append(('OK ' if c else 'FAIL ')+n+' '+str(x)[:250])
with sync_playwright() as p:
    b=p.chromium.launch(); pg=b.new_page(viewport={'width':420,'height':900}); errs=[]
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.clock.install(time=datetime.datetime.fromisoformat('2026-10-08T12:00:00'))
    pg.goto('http://localhost:8765/kp_test.html'); pg.clock.run_for(600)
    A=pg.locator('#a kinderpunkte-card'); B=pg.locator('#b kinderpunkte-card'); t=lambda ms=400: pg.clock.run_for(ms); ev=lambda x: pg.evaluate(x); html=lambda: ev("A.shadowRoot.innerHTML")
    ev("A._save('kid','K',{name:'Kai',emoji:'🐻',by:2016,bm:3,bd:1})"); t(1000)
    ok('off by default', 'data-a="grade"' not in html() and 'data-a="kgrade"' not in ev("B.shadowRoot.innerHTML"))
    ev("A._setCfg({gradesOn:true, hc:'DE', targets:['mobile_app_phone_a'], nTask:true})"); t(800)
    ok('scale DE', ev("A._gScale().id")=='de')
    ok('stars 1/2/3/4/5', ev("[1,2,2.5,3,4,5].map(g=>A._gStars(g))")==[10,6,3,3,0,0], ev("[1,2,2.5,3,4,5].map(g=>A._gStars(g))"))
    ev("A._setCfg({hc:'CH'})"); t(300)
    ok('CH high best', ev("A._gScale().id")=='ch' and ev("A._gStars(6)")==10 and ev("A._gStars(4.5)")==3 and ev("A._gStars(3)")==0)
    ev("A._setCfg({hc:'FR'})"); t(300); ok('FR 0-20', ev("A._gStars(17)")==8)
    ev("A._setCfg({hc:'DE'})"); t(300)
    # Einstellungen
    A.locator('[data-a="tab"][data-id="einst"]').click(); t()
    h=html(); ok('settings shown', 'data-gst="0"' in h and 'gImp' in h and 'data-id="f_gradesOn"' in h)
    ev("(()=>{const i=A.shadowRoot.querySelector('[data-gst=\"0\"]'); i.value='12'; i.dispatchEvent(new Event('change',{bubbles:true,composed:true}));})()"); t(500)
    ok('own star table', ev("A._gStars(1)")==12 and ev("A._gStars(2)")==6, ev("A._cfg.gStars"))
    # Eltern: Note eintragen
    A.locator('[data-a="tab"][data-id="kinder"]').click(); t()
    A.locator('[data-a="grade"]').first.click(); t()
    ev("(()=>{const m=A.shadowRoot.querySelector('#modal'); m.querySelector('[name=gsub]').value='Mathe'; m.querySelector('[name=gval]').value='2';})()")
    A.locator('[data-a="msave"]').click(); t(800)
    k=ev("A._db.kid.K"); ok('booked 2 -> 6', k['points']==6 and k['grades'][0]['g']==2, [k.get('points'), k.get('grades')])
    A.locator('[data-a="grade"]').first.click(); t()
    ev("(()=>{const m=A.shadowRoot.querySelector('#modal'); m.querySelector('[name=gsub]').value='mathe'; m.querySelector('[name=gval]').value='1';})()")
    A.locator('[data-a="msave"]').click(); t(800)
    k=ev("A._db.kid.K"); ok('improvement bonus', k['points']==6+12+3 and k['grades'][0].get('imp')==3, [k['points'], k['grades'][0]])
    ok('ledger', [x['r'] for x in k['ledger'][:2]]==['🎓 Verbesserung: mathe','🎓 mathe: Note 1'], [x['r'] for x in k['ledger'][:3]])
    ok('family goal counts', ev("A._cfg.famPts || (A._db.cfg && 0)")!=None)
    # Zeugnis
    A.locator('[data-a="grade"]').first.click(); t()
    ok('overview', 'Notenübersicht' in ev("A.shadowRoot.querySelector('#modal').innerText") and '📈' in ev("A.shadowRoot.querySelector('#modal').innerText"))
    ev("A.shadowRoot.querySelector('#modal [name=grep]').checked=true"); A.locator('[data-a="msave"]').click(); t(800)
    ok('report bonus', ev("A._db.kid.K.points")==41, ev("A._db.kid.K.points"))
    # bad input
    A.locator('[data-a="grade"]').first.click(); t()
    ev("(()=>{const m=A.shadowRoot.querySelector('#modal'); m.querySelector('[name=gsub]').value='Deutsch'; m.querySelector('[name=gval]').value='9';})()")
    A.locator('[data-a="msave"]').click(); t(300)
    ok('invalid grade kept modal', ev("A.shadowRoot.querySelector('#modal').classList.contains('open')"))
    ev("A._closeModal()"); t()
    # Kind meldet
    ev("B._opens={K:true}; B._render()"); t()
    ok('kid button', 'data-a="kgrade"' in ev("B.shadowRoot.innerHTML"))
    ev("B._gradeDlg('K', true)"); t()
    ev("(()=>{const m=B.shadowRoot.querySelector('#modal'); m.querySelector('[name=gsub]').value='Englisch'; m.querySelector('[name=gval]').value='1.5';})()")
    B.locator('[data-a="msave"]').click(); t(1500)
    q=ev("Object.values(A._db.req).find(q=>q.grade)"); ok('request created', q and q['grade']['g']==1.5, q)
    ok('push with buttons', 'gok' in str(ev("window.ndata")), ev("window.ndata"))
    ok('kid sees waiting', 'Englisch' in ev("B.shadowRoot.innerHTML"))
    ok('B modal closed', not ev("B.shadowRoot.querySelector('#modal').classList.contains('open')"), ev("B.shadowRoot.querySelector('#modal').innerText")[:200])
    ev("A.shadowRoot.querySelector('[data-a=\"tab\"][data-id=\"heute\"]').click()"); t()
    ok('approval row', 'data-a="gapr"' in html())
    ev("A.shadowRoot.querySelector('[data-a=\"gapr\"]').click()"); t(800)
    ok('approved +6', ev("A._db.kid.K.points")==47 and not ev("Object.values(A._db.req).some(q=>q.grade)"), ev("A._db.kid.K.points"))
    # Knopf aus Push: ablehnen
    ev("B._gradeDlg('K', true)"); t()
    ev("(()=>{const m=B.shadowRoot.querySelector('#modal'); m.querySelector('[name=gsub]').value='Sport'; m.querySelector('[name=gval]').value='1';})()")
    B.locator('[data-a="msave"]').click(); t(1500)
    rid=ev("Object.values(A._db.req).find(q=>q.grade).id")
    ev(f"A._actRun('KP','gno','{rid}')"); t(800)
    ok('rejected by button', not ev("Object.values(A._db.req).some(q=>q.grade)") and ev("A._db.kid.K.points")==47)
    # Übersetzung Verlauf
    ok('reasonT', ev("A._reasonT('🎓 Mathe: Note 2')")=='🎓 Mathe: Note 2')
    ok('no errors', not errs, errs)
    b.close()
print('\n'.join(R))
