from playwright.sync_api import sync_playwright
import datetime
R=[]
def ok(n,c,x=''): R.append(('OK ' if c else 'FAIL ')+n+' '+str(x)[:250])
with sync_playwright() as p:
    b=p.chromium.launch(); pg=b.new_page(viewport={'width':420,'height':900}); errs=[]
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.clock.install(time=datetime.datetime.fromisoformat('2026-10-08T12:00:00'))
    pg.goto('http://localhost:8765/kp_test.html'); pg.clock.run_for(600)
    t=lambda ms=400: pg.clock.run_for(ms); ev=pg.evaluate; app=lambda: ev("A.shadowRoot.querySelector('#app').innerText")
    ev("A._save('kid','K',{name:'Kai',emoji:'🐻',by:2018})"); ev("A._save('kid','L',{name:'Lia',emoji:'🦊',by:2020})"); t(400)
    ev("A._save('task','T1',{title:'Zimmer aufräumen',emoji:'🧸',points:3,kids:['K'],sched:'week',days:[]})"); ev("A._save('task','T2',{title:'Bett machen',emoji:'🛏️',points:1,kids:['L'],sched:'week',days:[]})"); t(400)
    ev("A._setSt('2026-10-08','T1','K','p')"); t(400)
    ok('approvals on heute', 'Freigaben' in app())
    ok('tab badge', ev("!!A.shadowRoot.querySelector('.tab .tbadge')"))
    ev("A.shadowRoot.querySelector('[data-a=\"tab\"][data-id=\"aufgaben\"]').click()"); t()
    ok('no approvals on aufgaben', 'Freigaben' not in app())
    ev("A.shadowRoot.querySelector('[data-a=tkf][data-k=L]').click()"); t()
    tx=app(); ok('filter Lia', 'Bett machen' in tx and 'Zimmer aufräumen' not in tx)
    ev("A.shadowRoot.querySelector('[data-a=tkf][data-k=\"\"]').click()"); t()
    ok('filter all', 'Zimmer aufräumen' in app())
    ev("A.shadowRoot.querySelector('.tkf [data-a=etask]').click()"); t()
    ev("(()=>{const i=A.shadowRoot.querySelector('#modal [name=tplq]'); i.value='zähne'; i.dispatchEvent(new Event('input',{bubbles:true,composed:true}));})()"); t()
    vis=ev("[...A.shadowRoot.querySelectorAll('#modal .qp[data-i]')].filter(q=>q.style.display!=='none').map(q=>q.innerText.split('\\n')[1]||q.innerText)")
    ok('search', len(vis)>=2 and all('ähne' in v for v in vis), vis)
    ev("A._closeModal()"); t()
    ev("A.shadowRoot.querySelector('[data-a=\"tab\"][data-id=\"einst\"]').click()"); t()
    tx=app(); ok('groups', all(g in tx.upper() for g in ['ALLGEMEIN','AUFGABEN & TAGESABLAUF','PUNKTE & BONI','BELOHNUNGEN & GELD','BENACHRICHTIGUNGEN','GERÄTE & SPRACHE','AUSWERTUNG','DATEN']), tx[:300])
    ev("A._setCfg({fam:{title:'Zoo',emoji:'🦁',cost:100,pts:10}})"); t()
    ok('famMinus in Freigabe', 'famMinus' in ev("A.shadowRoot.querySelector('.acch[data-id=appr]').closest('.acc').innerHTML"))
    ok('features sorted by topic', ev("(()=>{const g={};let cur='';[...A.shadowRoot.querySelectorAll('.accgrp, .acch')].forEach(e=>{if(e.classList.contains('accgrp'))cur=e.textContent;else g[e.dataset.id]=cur;});return g['f_dayBlocks'].includes('Aufgaben')&&g['f_wbOn'].includes('Punkte')&&g['money'].includes('Belohnungen')&&g['f_voiceOn'].includes('Geräte')&&g['sec'].includes('Allgemein')&&g['trash'].includes('Daten')&&!g['feat']})()"))
    ok('no errors', not errs, errs)
    b.close()
print('\n'.join(R))
