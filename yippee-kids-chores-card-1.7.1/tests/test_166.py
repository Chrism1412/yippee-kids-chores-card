    ok('without option: heights differ (problem from #10)', len(set(h for _,h in ta+tb))>1, (ta,tb))
    ok('default: look css empty', ev("A.shadowRoot.getElementById('look').textContent")=='')
    # ---- global einschalten (⚙️ → 🎨 Darstellung)
    ev("A._setCfg({vEqual:true})"); t(1200)
    ta=ev(f"({TILES})(A)"); tb=ev(f"({TILES})(B)")
    hs=set(h for _,h in ta+tb)
    ok('equal: all tiles same height in both cards', len(hs)==1, (ta,tb))
    ra=sorted(set(y for y,_ in ta)); rb=sorted(set(y for y,_ in tb))
    ok('equal: rows line up side by side', ra[:3]==rb[:3] or [y-ra[0] for y in ra[:3]]==[y-rb[0] for y in rb[:3]], (ra,rb))
    ok('equal applies to second card too (global cfg)', 'line-clamp:3' in ev("B.shadowRoot.getElementById('look').textContent"))
    long=ev("""(()=>{const s=[...A.shadowRoot.querySelectorAll('.tile .t>span')].find(x=>x.textContent.startsWith('Ein wirklich')); const r=s.getBoundingClientRect(), tl=s.closest('.tile').getBoundingClientRect(); return [s.scrollHeight>s.clientHeight+2, r.bottom<=tl.bottom, s.textContent.length]})()""")
    ok('long name clamped, full text kept', long[0] and long[1] and long[2]>80, long)
    short=ev("""(()=>{const s=[...A.shadowRoot.querySelectorAll('.tile .t>span')].find(x=>x.textContent==='Tisch decken'); return s.scrollHeight<=s.clientHeight+1})()""")
    ok('short name not clamped', short)
    ok('three-line name fully visible', ev("""(()=>{const s=[...B.shadowRoot.querySelectorAll('.tile .t>span')].find(x=>x.textContent.startsWith('Zimmer kurz')); return s.scrollHeight<=s.clientHeight+1})()"""))
    # Wartet auf Freigabe (längere Info) ändert die Höhe nicht
    ev("A._kidTap('a1','K',null)"); t(1200)
    ta2=ev(f"({TILES})(A)")
    ok('waiting tile (2-line info) keeps height', set(h for _,h in ta2)==hs, (ta2,hs))
    pg.screenshot(path='t166_equal.png', clip={'x':0,'y':0,'width':900,'height':1500})
    # ---- Karten-Editor hat Vorrang
    ev("B.setConfig({storage:'todo.kinderpunkte',mode:'kid',child:'Ben',equal_tiles:false})"); t(600)
    ok('card equal_tiles:false beats global on', 'line-clamp' not in ev("B.shadowRoot.getElementById('look').textContent"))
    ev("A._setCfg({vEqual:false})"); t(800)
    ev("B.setConfig({storage:'todo.kinderpunkte',mode:'kid',child:'Ben',equal_tiles:true})"); t(600)
    ok('card equal_tiles:true beats global off', 'line-clamp:3' in ev("B.shadowRoot.getElementById('look').textContent") and 'line-clamp' not in ev("A.shadowRoot.getElementById('look').textContent"))
    ev("A._setCfg({vCompact:true,vTransp:true,vScale:'110'})"); t(800)
    css=ev("A.shadowRoot.getElementById('look').textContent")
    ok('global compact/transparent/scale', 'min-height:96px' in css and 'transparent' in css and 'zoom:1.1' in css, css)
    ev("B.setConfig({storage:'todo.kinderpunkte',mode:'kid',child:'Ben',compact:false,transparent:false,scale:100})"); t(600)
    css=ev("B.shadowRoot.getElementById('look').textContent")
    ok('card values beat global (off / 100 %)', 'min-height:96px' not in css and 'background:transparent' not in css and 'zoom' not in css, css)
    ev("B.setConfig({storage:'todo.kinderpunkte',mode:'kid',child:'Ben',scale:'90'})"); t(600)
    ok('card scale beats global', 'zoom:0.9' in ev("B.shadowRoot.getElementById('look').textContent"))
    ev("A._setCfg({vCompact:false,vTransp:false,vScale:''})"); t(800)
    ev("B.setConfig({storage:'todo.kinderpunkte',mode:'kids'})"); t(600)
    ok('everything back to default', ev("B.shadowRoot.getElementById('look').textContent")=='')
    # ---- ⚙️ Einstellungen
    ev("A.setConfig({storage:'todo.kinderpunkte',mode:'admin',notify:'notify.mobile_app_parent'}); A._setCfg({setView:'all'}); A._accAll=false; A._accOpen='look'; A._tab='einst'; A._render()"); t(800)
    ids=ev("[...A.shadowRoot.querySelectorAll('.acch')].map(x=>x.dataset.id)")
    ok('look section right after language', ids[:2]==['lang','look'], ids[:4])
    ok('summary says Standard', 'Standard' in ev("A.shadowRoot.querySelector('.acch[data-id=look]').textContent"))
    ok('section has 3 switches + size', ev("['vEqual','vCompact','vTransp'].every(k=>!!A.shadowRoot.querySelector('input[data-k='+k+']')) && !!A.shadowRoot.querySelector('select[data-cfgs=vScale]')"))
    ok('handbook button in section', ev("!!A.shadowRoot.querySelector('.acc.open [data-a=hbtopic], .acc.open .hbbtn, .acc.open [data-topic]')") or 'Handbuch' in ev("A.shadowRoot.querySelector('.acc.open').textContent"))
    pg.locator('input[data-k=vEqual]').check(); t(1200)
    ok('switch saves vEqual', ev("A._cfg.vEqual")==True)
    ok('kids card follows switch', 'line-clamp:3' in ev("B.shadowRoot.getElementById('look').textContent"))
    ok('summary updates', 'Gleich hohe Kacheln' in ev("A.shadowRoot.querySelector('.acch[data-id=look]').textContent"))
    pg.locator('select[data-cfgs=vScale]').select_option('120'); t(1200)
    ok('size select saves', str(ev("A._cfg.vScale"))=='120' and 'zoom:1.2' in ev("B.shadowRoot.getElementById('look').textContent"))
    ok('summary shows size', '120 %' in ev("A.shadowRoot.querySelector('.acch[data-id=look]').textContent"))
    pg.screenshot(path='t166_settings.png', clip={'x':0,'y':0,'width':900,'height':1100})
    pg.locator('select[data-cfgs=vScale]').select_option(''); t(800)
    pg.locator('input[data-k=vEqual]').uncheck(); t(1200)
    ok('switch off again', not ev("A._cfg.vEqual") and ev("B.shadowRoot.getElementById('look').textContent")=='')
    # Suche
    ev("A._accOpen=''; A._render()"); t(300)
    pg.locator('.setq').fill('Kacheln'); t(300)
    vis=ev("[...A.shadowRoot.querySelectorAll('.acc:not([hidden]) .acch')].map(x=>x.dataset.id)")
    ok('search finds look', vis[:1]==['look'], vis)
    pg.locator('.setq').fill('Aussehen'); t(300)
    ok('search keyword Aussehen', ev("[...A.shadowRoot.querySelectorAll('.acc:not([hidden]) .acch')].map(x=>x.dataset.id)")==['look'])
    pg.locator('.setq').fill(''); t(300)
    ev("A.shadowRoot.activeElement && A.shadowRoot.activeElement.blur()"); t(300)
    # Englisch
    ev("A._setCfg({lang:'en'})"); t(500); pg.wait_for_timeout(1500); t(300)
    ev("A._setQ=''; A._accAll=false; A._accOpen='look'; A._tab='einst'; A._render()"); t(500)
    h=ev("(A.shadowRoot.querySelector('.acc.open')||{}).textContent||A._accOpen")
    ok('english texts', 'Equal-height tiles' in h and 'Applies to all Yippee! cards' in h and 'Gleich' not in h, h[:300])
    ev("A._setCfg({lang:'de'})"); t(500); pg.wait_for_timeout(1500); t(300)
    # ---- Karten-Editor: an / aus / wie in ⚙️
    ev("A._setCfg({vEqual:true,vScale:'110'})"); t(1200)
    ev("""(()=>{const e=document.createElement('yippee-kids-chores-card-editor'); document.body.appendChild(e); e.hass=A._hass; e.setConfig({storage:'todo.kinderpunkte',mode:'kid',child:'Mia',compact:true}); window.E=e; window.cfgOut=null; e.addEventListener('config-changed',x=>window.cfgOut=x.detail.config);})()"""); t(500)
