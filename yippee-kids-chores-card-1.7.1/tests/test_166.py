    ok('editor shows existing compact:true as on', ev("E.shadowRoot.querySelector('select[data-k=compact]').value")=='on')
    t(800)
    ok('editor shows current global value', '(an)' in ev("E.shadowRoot.querySelector('select[data-k=equal_tiles] option[value=\"\"]').textContent") and '(aus)' in ev("E.shadowRoot.querySelector('select[data-k=transparent] option[value=\"\"]').textContent") and '(110 %)' in ev("E.shadowRoot.querySelector('select[data-k=scale] option[value=\"\"]').textContent"), ev("[...E.shadowRoot.querySelectorAll('select option[value=\"\"]')].map(o=>o.textContent)"))
    ok('editor default is as in settings', ev("E.shadowRoot.querySelector('select[data-k=equal_tiles]').value")=='' and ev("E.shadowRoot.querySelector('select[data-k=scale]').value")=='')
