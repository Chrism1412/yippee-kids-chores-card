    ev("window.items['todo.zweite']=[]; A._hass.states['todo.zweite']={state:'0',attributes:{friendly_name:'Zweite'}}; A.setConfig({storage:'todo.zweite',mode:'admin',wizard:false})"); t(1500)
    ok('switched to second list', ev("A._config.storage")=='todo.zweite' and ev("Object.keys(A._db.kid).length")==0, ev("Object.keys(A._db.kid)"))
    ev("A._setCfg({lang:'de'})"); t(800)
    ev("B._save('reward','OLD',{title:'Alt',emoji:'🧓',cost:5})"); t(800)
