    ok('rewards: long name clamped to 2 lines', ev("""(()=>{const t=[...A.shadowRoot.querySelectorAll('.rw .t')].find(x=>x.textContent.startsWith('Filmabend')); return t.scrollHeight>t.clientHeight+2})()"""))
