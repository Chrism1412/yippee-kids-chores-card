    b=p.chromium.launch(); pg=b.new_page(viewport={'width':420,'height':900}); errs=[]
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.clock.install(time=datetime.datetime.fromisoformat('2026-10-08T12:00:00'))
    pg.goto('http://localhost:8765/kp_test.html'); pg.clock.run_for(600)
    t=lambda ms=400: pg.clock.run_for(ms); ev=pg.evaluate; app=lambda: ev("A.shadowRoot.querySelector('#app').innerText")
    ev("localStorage.removeItem('kpTkg'); localStorage.removeItem('kpTkO')")
    ev("A._save('kid','K',{name:'Kai',emoji:'🐻',by:2018})"); ev("A._save('kid','L',{name:'Lia',emoji:'🦊',by:2020})"); t()
    ev("A._save('task','T1',{title:'Zimmer aufräumen',emoji:'🧸',points:3,kids:['K'],sched:'week',days:[],from:'18:00',to:'19:00'})")
    ev("A._save('task','T2',{title:'Bett machen',emoji:'🛏️',points:1,kids:['K','L'],sched:'week',days:[],from:'07:00',to:'08:00'})")
    ev("A._save('task','T3',{title:'Ranzen packen',emoji:'🎒',points:1,kids:['L'],sched:'week',days:[],school:true})")
    ev("A._save('task','T4',{title:'Müll extra',emoji:'🗑️',points:2,kids:['K'],sched:'once'})")
    ev("A._save('task','T5',{title:'Verwaist',emoji:'❓',points:1,kids:[],sched:'week',days:[]})"); t()
    ev("A.shadowRoot.querySelector('[data-a=\"tab\"][data-id=\"aufgaben\"]').click()"); t()
    tx=app()
    ok('kid headers', '🐻 Kai' in tx and '🦊 Lia' in tx and 'Ohne Kind' in tx, tx[:400])
    ok('time groups default', 'Morgens' in tx and 'Abends' in tx and 'Ohne Zeit' in tx)
    ok('shared marked', 'mit Lia' in tx and 'mit Kai' in tx)
    ok('shared task in both kids', ev("A.shadowRoot.querySelectorAll('[data-a=etask][data-id=T2]').length")==2)
    ok('school instead of täglich', 'nur an Schultagen' in tx and 'täglich · 🎒' not in tx)
    # Kai: Morgens (Bett) vor Abends (Zimmer)
    ok('sorted by time', tx.index('Bett machen') < tx.index('Zimmer aufräumen'))
    ok('counts', ev("A.shadowRoot.querySelector('[data-a=tkfold][data-id=\"k:K\"] .tkn').innerText")=='3')
    # Art
    ev("A.shadowRoot.querySelector('[data-a=tkg][data-m=art]').click()"); t(); tx=app()
    ok('art groups', 'Pflichtaufgaben' in tx and 'Sonderaufgaben' in tx and 'Morgens' not in tx, tx[:400])
    ok('mode stored', ev("localStorage.getItem('kpTkg')")=='art')
    ev("A.shadowRoot.querySelector('[data-a=tkg][data-m=none]').click()"); t(); tx=app()
    ok('none', 'Pflichtaufgaben' not in tx and 'Morgens' not in tx and 'Bett machen' in tx)
    # Einklappen
    ev("A.shadowRoot.querySelector('[data-a=tkfold][data-id=\"k:K\"]').click()"); t(); tx=app()
    ok('collapse kid', 'Zimmer aufräumen' not in tx and 'Ranzen packen' in tx, tx[:300])
    ok('collapse stored', ev("JSON.parse(localStorage.getItem('kpTkO'))['k:K']")==False)
    ev("A.shadowRoot.querySelector('[data-a=tkfold][data-id=\"k:K\"]').click()"); t()
    ok('expand kid', 'Zimmer aufräumen' in app())
    # Filter je Kind
    ev("A.shadowRoot.querySelector('[data-a=tkf][data-k=L]').click()"); t(); tx=app()
    ok('filter Lia', 'Ranzen packen' in tx and 'Zimmer aufräumen' not in tx and 'Ohne Kind' not in tx)
    ev("A.shadowRoot.querySelector('[data-a=tkf][data-k=\"\"]').click()"); t()
    # Reihenfolge innerhalb Kind + Gruppe
    ev("A.shadowRoot.querySelector('[data-a=tkg][data-m=zeit]').click()"); t()
    ev("A._setCfg({orderOn:true})"); t()
    ok('order buttons carry kid', ev("A.shadowRoot.querySelector('[data-a=tup][data-id=T1]').dataset.k")=='K')
    # Englisch
    ev("A._setCfg({lang:'en'})"); t(500); pg.wait_for_timeout(1500); t(300)
    tx=app(); ok('english', 'Time of day' in tx or 'Group by' in tx, tx[:300])
    # 1.5.0: neue Routinen + Mittagsschlaf
    ev("A._setCfg({lang:'de',routOn:true})"); t(500); pg.wait_for_timeout(800); t(300)
    ev("A._closeModal&&A._closeModal(); A._editTask(null, true)") if False else None
    ev("A._tab='aufgaben'; A._render()"); t()
