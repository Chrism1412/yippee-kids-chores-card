    ev("A._closeModal()"); t(); ev("A._editTask(null)"); t()
    ok('nap task template', 'Mittagsschlaf' in ev("A.shadowRoot.querySelector('#modal').textContent"))
    ev("A._closeModal()"); t()
    # 1.5.0: Samstagsschule beim Kind
    ev("A._save('kid','S',{name:'Sara',emoji:'🐱',sat:true})"); t()
    ev("A._save('task','SC',{title:'Hausaufgaben machen',emoji:'📝',points:2,kids:['K','S'],sched:'week',days:[1,2,3,4,5],school:true})")
    ev("A._save('task','PV',{title:'Ranzen für morgen packen',emoji:'🎒',points:1,kids:['K','S'],sched:'week',days:[0,1,2,3,4],school:true,schoolPrev:true})"); t()
