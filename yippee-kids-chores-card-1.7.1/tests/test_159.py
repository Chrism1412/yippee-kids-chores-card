    ok('sat: normal kid no school', ev(f"A._isFor(A._db.task.SC,'K',{sat})")==False)
    ok('sat: sat kid school', ev(f"A._isFor(A._db.task.SC,'S',{sat})")==True)
    ok('sun: nobody', ev(f"A._isFor(A._db.task.SC,'S',{sun})")==False)
    ok('fri evening prev: only sat kid', ev(f"A._isFor(A._db.task.PV,'S',{fri})")==True and ev(f"A._isFor(A._db.task.PV,'K',{fri})")==False)
    ok('weekday both', ev(f"A._isFor(A._db.task.SC,'K',{fri})") and ev(f"A._isFor(A._db.task.SC,'S',{fri})"))
    ev("A._editKid('S')"); t()
